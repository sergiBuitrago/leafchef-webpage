import {readFile, writeFile, mkdir} from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const languages = ['de', 'es', 'fr'];
const pages = ['index', 'legal', 'impressum', 'privacy', 'terms'];
const check = process.argv.includes('--check');
const site = 'https://leafchef.app';
const stripSiteSchema = html => html.replace(/<script type="application\/ld\+json" id="site-schema">[^]*?<\/script>\s*/g, '');
const pageUrl = (page, language) => `${site}/${page === 'index' && language === 'en' ? '' : `${page}${language === 'en' ? '' : '.' + language}.html`}`;
function searchMetadata(html, page, language) {
  html = stripSiteSchema(html).replace(/<link rel="(?:canonical|alternate)"[^>]*>\s*/g, '').replace(/<meta property="og:(?:url|site_name)"[^>]*>\s*/g, '');
  const canonical = pageUrl(page, language);
  const alternates = ['en', ...languages].map(lang => `<link rel="alternate" hreflang="${lang}" href="${pageUrl(page, lang)}">`).join('\n  ');
  const metadata = `<link rel="canonical" href="${canonical}">\n  <meta property="og:url" content="${canonical}">\n  ${alternates}\n  <link rel="alternate" hreflang="x-default" href="${pageUrl(page, 'en')}">\n`;
  const siteName = page === 'index' ? '  <meta property="og:site_name" content="LeafChef">\n' : '';
  // Google's site-name markup belongs on the domain's root home page.
  const schema = page === 'index' && language === 'en'
    ? `  <script type="application/ld+json" id="site-schema">${JSON.stringify({'@context':'https://schema.org','@type':'WebSite',name:'LeafChef',url:site+'/'})}</script>\n` : '';
  return html.replace('</head>', metadata + siteName + schema + '</head>');
}
const runtime = JSON.parse(await readFile(new URL('locales/runtime.json', root), 'utf8'));
const invariant = /^(?:LeafChef|© 2026 LeafChef|Sergi Buitrago Llorente|Britzer Strasse 62C|12109 Berlin|sergi\.buitrago@gmail\.com|leafchef\.web\.interest\.submitted\.v1|English|Deutsch|Español|Français|[\d\s+✓↗▴▰©/–.,:]+|\d+ g)$/u;
const escape = value => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
async function output(path, content) {
  const target = new URL(path, root);
  content = content.replaceAll('\r\n', '\n');
  if (check) {
    if ((await readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== content) throw new Error(`Stale translation: ${path}. Run npm run localize.`);
  } else await writeFile(target, content);
}
// Keep the English source and generated translations consistent and reciprocal.
for (const page of pages) {
  const path = `public/${page}.html`;
  await output(path, searchMetadata(await readFile(new URL(path, root), 'utf8'), page, 'en'));
}
for (const language of languages) {
  const messages = JSON.parse(await readFile(new URL(`locales/${language}.json`, root), 'utf8'));
  for (const [key, translations] of Object.entries(runtime)) {
    if (!translations[language]) throw new Error(`Missing ${language} interactive translation: ${key}`);
    messages[key] = translations[language];
  }
  const translate = text => {
    if (Object.hasOwn(messages, text)) return messages[text];
    if (invariant.test(text)) return text;
    throw new Error(`Missing ${language} translation: ${text}`);
  };
  for (const page of pages) {
    let html = stripSiteSchema(await readFile(new URL(`public/${page}.html`, root), 'utf8'));
    html = html.split(/(<[^>]*>)/).map(part => {
      if (!part.startsWith('<')) return part.trim() ? part.replace(part.trim(), escape(translate(part.trim()))) : part;
      return part.replace(/\b(aria-label|alt)="([^"]+)"/g, (_, key, value) => `${key}="${escape(translate(value))}"`)
        .replace(/(<meta (?:name="description"|property="og:(?:title|description)") content=")([^"]+)(")/g, (_, start, value, end) => start + escape(translate(value)) + end);
    }).join('');
    html = html.replace('<html lang="en">', `<html lang="${language}">`);
    // Only local document links change; assets and external provider links stay intact.
    html = html.replace(/href="(index|legal|impressum|privacy|terms)\.html"(?! lang=)/g, `href="$1.${language}.html"`);
    html = html.replace(/<nav class="language-switcher[^]*?<\/nav>/, nav => nav.replaceAll(' aria-current="page"', '').replace(`hreflang="${language}"`, `hreflang="${language}" aria-current="page"`));
    if (page === 'index') html = html.replace('<script src="i18n.js"', `<script src="locales/${language}.js" defer></script>\n  <script src="i18n.js"`);
    html = searchMetadata(html, page, language);
    await output(`public/${page}.${language}.html`, html);
  }
  if (!check) await mkdir(new URL('public/locales/', root), {recursive:true});
  await output(`public/locales/${language}.js`, `// Generated by scripts/localize.mjs from locales/${language}.json.\nwindow.leafchefMessages = ${JSON.stringify(messages)};\n`);
}
const urls = ['en', ...languages].map(language => `  <url><loc>${pageUrl('index', language)}</loc></url>`).join('\n');
await output('public/sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`);
await output('public/robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${site}/sitemap.xml\n`);
console.log(check ? 'All translated pages are complete and current.' : 'Generated German, Spanish and French pages.');
